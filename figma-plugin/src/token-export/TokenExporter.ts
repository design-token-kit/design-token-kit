/**
 * Color value in the DTCG JSON format.
 */
export interface DtcgColorValue {
    colorSpace: "srgb" | DtcgPropertyReference;
    components: [number, number, number] | DtcgPropertyReference;
    alpha: number | DtcgPropertyReference;
}

/**
 * A DTCG property-level JSON Pointer reference.
 */
export interface DtcgPropertyReference {
    $ref: string;
}

/**
 * Color token in the DTCG JSON format.
 */
export interface DtcgColorToken {
    $type: "color";
    $value: DtcgColorValue | string;
    $description?: string;
}

/**
 * Dimension value in the DTCG JSON format.
 */
export interface DtcgDimensionValue {
    value: number;
    unit: "px";
}

/**
 * Dimension token in the DTCG JSON format.
 */
export interface DtcgDimensionToken {
    $type: "dimension";
    $value: DtcgDimensionValue | string;
    $description?: string;
}

/**
 * Number token in the DTCG JSON format.
 */
export interface DtcgNumberToken {
    $type: "number";
    $value: number | string;
    $description?: string;
}

/**
 * Font weight token in the DTCG JSON format.
 */
export interface DtcgFontWeightToken {
    $type: "fontWeight";
    $value: number | string;
    $description?: string;
}

/**
 * Typography value in the DTCG JSON format.
 */
export interface DtcgTypographyValue {
    fontFamily: string;
    fontSize: DtcgDimensionValue;
    fontWeight: number;
    letterSpacing: DtcgDimensionValue;
    lineHeight: number;
}

/**
 * Typography token in the DTCG JSON format.
 */
export interface DtcgTypographyToken {
    $type: "typography";
    $value: DtcgTypographyValue;
    $description?: string;
}

/**
 * Shadow layer value in the DTCG JSON format.
 */
export interface DtcgShadowLayer {
    color: DtcgColorValue;
    offsetX: DtcgDimensionValue;
    offsetY: DtcgDimensionValue;
    blur: DtcgDimensionValue;
    spread: DtcgDimensionValue;
    inset?: boolean;
}

/**
 * Shadow token in the DTCG JSON format.
 */
export interface DtcgShadowToken {
    $type: "shadow";
    $value: DtcgShadowLayer | DtcgShadowLayer[];
    $description?: string;
}

/**
 * Mutable DTCG token document assembled for export.
 */
export interface DtcgTokenDocument {
    [key: string]: unknown;
}

/**
 * Token with its target path inside a DTCG document.
 */
export interface DtcgTokenEntry {
    path: string[];
    token: DtcgToken;
    architectureWarnings?: string[];
}

/**
 * Token file generated by the Figma exporter.
 */
export interface ExportedTokenFile {
    fileName: string;
    content: string;
    tokens: DtcgTokenDocument;
    downloadable: boolean;
    architectureWarnings: string[];
}

/**
 * Aggregate token export statistics.
 */
export interface TokenExportSummary {
    source: "variables" | "styles" | "empty";
    colorTokens: number;
    dimensionTokens: number;
    numberTokens: number;
    typographyTokens: number;
    shadowTokens: number;
    skipped: number;
}

/**
 * Full token export result returned to the plugin UI.
 */
export interface TokenExportResult {
    files: ExportedTokenFile[];
    summary: TokenExportSummary;
    warnings: string[];
}

interface VariableTokenReadResult {
    foundVariables: boolean;
    files: ExportedTokenFile[];
}

interface ModeExport {
    fileName: string;
    modeIdByCollectionId: Map<string, string>;
    base: boolean;
}

const DIMENSION_SCOPES: VariableScope[] = ["GAP", "CORNER_RADIUS", "WIDTH_HEIGHT", "STROKE_FLOAT"];

export class TokenExporter {
    readonly #documentBuilder = new TokenDocumentBuilder();
    readonly #tokenCounter = new TokenCounter();

    async export(): Promise<TokenExportResult> {
        const warnings: string[] = [];
        const variableResult = await readColorVariableTokens(warnings, this.#documentBuilder);
        const textStyleTokens = await readTextStyleTokens(warnings);
        const effectStyleTokens = await readEffectStyleTokens(warnings);
        const styleTokens = !variableResult.foundVariables
            ? await readColorStyleTokens(warnings)
            : [];
        const source = variableResult.foundVariables
            ? "variables"
            : styleTokens.length > 0 || textStyleTokens.length > 0 || effectStyleTokens.length > 0 ? "styles" : "empty";
        const baseStyleTokens = [...styleTokens, ...textStyleTokens, ...effectStyleTokens];
        const styleDocument = this.#documentBuilder.build(baseStyleTokens);
        const files = variableResult.foundVariables
            ? addTokensToBaseFile(
                variableResult.files,
                [...textStyleTokens, ...effectStyleTokens],
                this.#documentBuilder,
            )
            : [{
                fileName: "tokens.json",
                content: JSON.stringify(styleDocument, null, 2),
                tokens: styleDocument,
                downloadable: baseStyleTokens.length > 0,
                architectureWarnings: collectArchitectureWarnings(baseStyleTokens),
            }];
        const counts = files.reduce(
            (value, file) => this.#tokenCounter.add(value, this.#tokenCounter.count(file.tokens)),
            this.#tokenCounter.empty(),
        );

        return {
            files,
            summary: {
                source,
                colorTokens: counts.colorTokens,
                dimensionTokens: counts.dimensionTokens,
                numberTokens: counts.numberTokens,
                typographyTokens: counts.typographyTokens,
                shadowTokens: counts.shadowTokens,
                skipped: warnings.filter((warning) => warning.startsWith("Skipped ")).length,
            },
            warnings,
        };
    }

}

async function readColorVariableTokens(
    warnings: string[],
    documentBuilder: TokenDocumentBuilder,
): Promise<VariableTokenReadResult> {
    if (figma.variables === undefined) {
        warnings.push("Figma Variables API is unavailable. Falling back to paint styles.");
        return { foundVariables: false, files: [] };
    }

    let variables: Variable[];
    try {
        const [colorVariables, floatVariables] = await Promise.all([
            figma.variables.getLocalVariablesAsync("COLOR"),
            figma.variables.getLocalVariablesAsync("FLOAT"),
        ]);
        variables = uniqueVariables([
            ...colorVariables.filter((variable) => getVariableResolvedType(variable) === "COLOR"),
            ...floatVariables.filter((variable) => getVariableResolvedType(variable) === "FLOAT"),
        ]);
    } catch (error: unknown) {
        warnings.push(
            `Could not read Figma color or float variables: ${getErrorMessage(error)}. `
                + "Falling back to paint styles.",
        );
        return { foundVariables: false, files: [] };
    }

    if (variables.length === 0) {
        return { foundVariables: false, files: [] };
    }

    const variablePathIndex = createVariablePathIndex(variables);
    const variableTokenTypeIndex = createVariableTokenTypeIndex(variables);
    const variableIndex = createVariableIndex(variables);
    const modeExports = await createModeExports(variables, warnings);
    const files = modeExports.map((modeExport) => {
        const tokens = readVariableTokensForMode(
            variables,
            variablePathIndex,
            variableTokenTypeIndex,
            variableIndex,
            modeExport,
            warnings,
        );
        const document = documentBuilder.build(tokens);

        return {
            fileName: modeExport.fileName,
            content: JSON.stringify(document, null, 2),
            tokens: document,
            downloadable: tokens.length > 0,
            architectureWarnings: collectArchitectureWarnings(tokens),
        };
    });
    const downloadableFiles = files.filter((file) => file.downloadable);

    return {
        foundVariables: true,
        files: downloadableFiles.length > 0 ? downloadableFiles : files.slice(0, 1),
    };
}

function readVariableTokensForMode(
    variables: Variable[],
    variablePathIndex: VariablePathIndex,
    variableTokenTypeIndex: VariableTokenTypeIndex,
    variableIndex: VariableIndex,
    modeExport: ModeExport,
    warnings: string[],
): DtcgTokenEntry[] {
    return variables.flatMap((variable) => {
        const tokenType = toTokenType(variable);
        const resolvedTypeName = getVariableResolvedType(variable).toLowerCase();
        if (tokenType === undefined) {
            return [];
        }

        const nameMapping = mapVariableTokenName(variable, tokenType);
        if (nameMapping === undefined) {
            warnings.push(
                `Skipped ${resolvedTypeName} variable "${variable.name}" `
                    + "because it does not contain a valid token path.",
            );
            return [];
        }

        const modeId = getModeId(variable, modeExport);
        const tokenValue = modeId === undefined
            ? undefined
            : toTokenValue(
                variable.valuesByMode[modeId],
                variablePathIndex,
                variableTokenTypeIndex,
                variableIndex,
                modeExport,
                tokenType,
            );
        if (tokenValue === undefined) {
            if (modeExport.base) {
                warnings.push(
                    `Skipped ${resolvedTypeName} variable "${variable.name}" in ${modeExport.fileName} `
                        + "because it has no raw value or resolvable alias.",
                );
            }
            return [];
        }

        return [{
            path: nameMapping.path,
            token: createToken(tokenType, tokenValue, variable.description),
            architectureWarnings: nameMapping.architectureWarnings,
        }];
    });
}

async function readColorStyleTokens(warnings: string[]): Promise<DtcgTokenEntry[]> {
    const styles = await figma.getLocalPaintStylesAsync();

    return styles.flatMap((style) => {
        const nameMapping = mapColorTokenName(style.name);
        if (nameMapping === undefined) {
            warnings.push(`Skipped paint style "${style.name}" because it does not contain a valid token path.`);
            return [];
        }

        const paint = style.paints.find(isVisibleSolidPaint);
        if (paint === undefined) {
            warnings.push(`Skipped paint style "${style.name}" because it has no visible solid paint.`);
            return [];
        }

        return [{
            path: nameMapping.path,
            token: createToken("color", { ...paint.color, a: paint.opacity ?? 1 }, style.description),
            architectureWarnings: nameMapping.architectureWarnings,
        }];
    });
}

async function readTextStyleTokens(warnings: string[]): Promise<DtcgTokenEntry[]> {
    if (typeof figma.getLocalTextStylesAsync !== "function") {
        return [];
    }

    const styles = await figma.getLocalTextStylesAsync();

    return styles.flatMap((style) => {
        const nameMapping = mapTokenName(style.name, ["primitive", "typography"]);
        if (nameMapping === undefined) {
            warnings.push(`Skipped text style "${style.name}" because it does not contain a valid token path.`);
            return [];
        }

        return [{
            path: nameMapping.path,
            token: createTypographyToken(style),
            architectureWarnings: nameMapping.architectureWarnings,
        }];
    });
}

async function readEffectStyleTokens(warnings: string[]): Promise<DtcgTokenEntry[]> {
    if (typeof figma.getLocalEffectStylesAsync !== "function") {
        return [];
    }

    const styles = await figma.getLocalEffectStylesAsync();

    return styles.flatMap((style) => {
        const nameMapping = mapTokenName(style.name, ["primitive", "shadow"]);
        if (nameMapping === undefined) {
            warnings.push(`Skipped effect style "${style.name}" because it does not contain a valid token path.`);
            return [];
        }

        const shadowLayers = style.effects
            .filter(isVisibleShadowEffect)
            .map(toShadowLayer);

        if (shadowLayers.length === 0) {
            warnings.push(`Skipped effect style "${style.name}" because it has no visible shadow effects.`);
            return [];
        }

        if (style.effects.some((effect) => effect.visible !== false && !isShadowEffect(effect))) {
            warnings.push(`Skipped unsupported non-shadow effects in effect style "${style.name}".`);
        }

        return [{
            path: nameMapping.path,
            token: createShadowToken(shadowLayers, style.description),
            architectureWarnings: nameMapping.architectureWarnings,
        }];
    });
}

function addTokensToBaseFile(
    files: ExportedTokenFile[],
    tokens: DtcgTokenEntry[],
    documentBuilder: TokenDocumentBuilder,
): ExportedTokenFile[] {
    if (tokens.length === 0) {
        return files;
    }

    const baseFileIndex = files.findIndex((file) => file.fileName === "tokens.json");
    const baseDocument = baseFileIndex === -1 ? {} : files[baseFileIndex]!.tokens;
    const document = documentBuilder.buildFrom(baseDocument, tokens);
    const baseFile = {
        fileName: "tokens.json",
        content: JSON.stringify(document, null, 2),
        tokens: document,
        downloadable: true,
        architectureWarnings: [
            ...(baseFileIndex === -1 ? [] : files[baseFileIndex]!.architectureWarnings),
            ...collectArchitectureWarnings(tokens),
        ],
    };

    if (baseFileIndex === -1) {
        return [baseFile, ...files];
    }

    return files.map((file, index) => index === baseFileIndex ? baseFile : file);
}

function collectArchitectureWarnings(tokens: DtcgTokenEntry[]): string[] {
    return tokens.flatMap((token) => token.architectureWarnings ?? []);
}

function createVariablePathIndex(variables: Variable[]): VariablePathIndex {
    const index: VariablePathIndex = new Map();

    for (const variable of variables) {
        const tokenType = toTokenType(variable);
        const nameMapping = tokenType === undefined ? undefined : mapVariableTokenName(variable, tokenType);
        if (nameMapping !== undefined) {
            index.set(variable.id, nameMapping.path);
        }
    }

    return index;
}

function createVariableTokenTypeIndex(variables: Variable[]): VariableTokenTypeIndex {
    const index: VariableTokenTypeIndex = new Map();

    for (const variable of variables) {
        const tokenType = toTokenType(variable);
        if (tokenType !== undefined) {
            index.set(variable.id, tokenType);
        }
    }

    return index;
}

function createVariableIndex(variables: Variable[]): VariableIndex {
    return new Map(variables.map((variable) => [variable.id, variable]));
}

function toTokenType(variable: Variable): DtcgVariableTokenType | undefined {
    const resolvedType = getVariableResolvedType(variable);
    if (resolvedType === "COLOR") {
        return "color";
    }

    if (resolvedType === "FLOAT") {
        if (isFontWeightVariable(variable)) {
            return "fontWeight";
        }

        return isNumberVariable(variable) ? "number" : "dimension";
    }

    return undefined;
}

function isNumberVariable(variable: Variable): boolean {
    const normalizedName = variable.name.toLowerCase().replace(/[^a-z0-9]+/g, "");
    const segments = variable.name
        .toLowerCase()
        .split("/")
        .map((segment) => segment.replace(/[^a-z0-9]+/g, ""));
    return getVariableScopes(variable).includes("OPACITY")
        || normalizedName.includes("opacity")
        || segments.some((segment) => ["opacity", "alpha", "number", "lineheight"].includes(segment));
}

function isFontWeightVariable(variable: Variable): boolean {
    const normalizedName = variable.name.toLowerCase().replace(/[^a-z0-9]+/g, "-");
    return normalizedName.includes("font-weight")
        || normalizedName.includes("fontweight")
        || getVariableScopes(variable).some((scope) => String(scope) === "FONT_WEIGHT");
}

function mapVariableTokenName(
    variable: Variable,
    tokenType: DtcgVariableTokenType,
): ReturnType<typeof mapColorTokenName> {
    if (tokenType === "color") {
        return mapColorTokenName(variable.name);
    }

    return mapTokenName(variable.name, toFloatFallbackPrefix(variable, tokenType));
}

function toFloatFallbackPrefix(variable: Variable, tokenType: "dimension" | "number" | "fontWeight"): string[] {
    if (tokenType === "fontWeight") {
        return ["primitive", "font-weight"];
    }

    if (tokenType === "number") {
        return isOpacityVariable(variable) ? ["primitive", "opacity"] : ["primitive", "number"];
    }

    const scope = getVariableScopes(variable).find((value) => DIMENSION_SCOPES.includes(value));
    if (scope === "GAP") {
        return ["primitive", "spacing"];
    }

    if (scope === "CORNER_RADIUS") {
        return ["primitive", "radius"];
    }

    if (scope === "WIDTH_HEIGHT") {
        return ["primitive", "size"];
    }

    if (scope === "STROKE_FLOAT") {
        return ["primitive", "border", "width"];
    }

    return ["primitive", inferDimensionGroup(variable.name)];
}

function getVariableResolvedType(variable: Variable): VariableResolvedDataType {
    if (variable.resolvedType !== undefined) {
        return variable.resolvedType;
    }

    const value = Object.values(variable.valuesByMode)[0];
    return typeof value === "number" ? "FLOAT" : "COLOR";
}

function getVariableScopes(variable: Variable): VariableScope[] {
    return variable.scopes ?? [];
}

function isOpacityVariable(variable: Variable): boolean {
    const normalizedName = variable.name.toLowerCase().replace(/[^a-z0-9]+/g, "");
    const segments = variable.name
        .toLowerCase()
        .split("/")
        .map((segment) => segment.replace(/[^a-z0-9]+/g, ""));
    return getVariableScopes(variable).includes("OPACITY")
        || normalizedName.includes("opacity")
        || segments.some((segment) => ["opacity", "alpha"].includes(segment));
}

function uniqueVariables(variables: Variable[]): Variable[] {
    return Array.from(new Map(variables.map((variable) => [variable.id, variable])).values());
}

function inferDimensionGroup(name: string): string {
    const normalized = name.toLowerCase();
    if (normalized.includes("radius")) {
        return "radius";
    }

    if (normalized.includes("size") || normalized.includes("width") || normalized.includes("height")) {
        return "size";
    }

    if (normalized.includes("border")) {
        return "border";
    }

    return "spacing";
}

async function createModeExports(variables: Variable[], warnings: string[]): Promise<ModeExport[]> {
    const collections = await readVariableCollections(warnings);
    const usedCollections = collections.filter((collection) =>
        variables.some((variable) => variable.variableCollectionId === collection.id),
    );

    if (usedCollections.length === 0) {
        return [{
            fileName: "tokens.json",
            modeIdByCollectionId: new Map(
                variables.map((variable) => [
                    variable.variableCollectionId,
                    Object.keys(variable.valuesByMode)[0] ?? "",
                ]),
            ),
            base: true,
        }];
    }

    const baseModeIds = new Map(usedCollections.map((collection) => [collection.id, collection.defaultModeId]));
    const themeModeExports = mergeThemeModeExports(usedCollections);

    return [
        {
            fileName: "tokens.json",
            modeIdByCollectionId: baseModeIds,
            base: true,
        },
        ...themeModeExports,
    ];
}

function mergeThemeModeExports(collections: VariableCollection[]): ModeExport[] {
    const modeExportsByFileName = new Map<string, ModeExport>();

    for (const collection of collections) {
        for (const mode of collection.modes) {
            if (mode.modeId === collection.defaultModeId) {
                continue;
            }

            const fileName = `tokens.${slugifyFileName(mode.name)}.json`;
            const existingExport = modeExportsByFileName.get(fileName);
            if (existingExport !== undefined) {
                existingExport.modeIdByCollectionId.set(collection.id, mode.modeId);
                continue;
            }

            modeExportsByFileName.set(fileName, {
                fileName,
                modeIdByCollectionId: new Map([[collection.id, mode.modeId]]),
                base: false,
            });
        }
    }

    return Array.from(modeExportsByFileName.values());
}

async function readVariableCollections(warnings: string[]): Promise<VariableCollection[]> {
    if (typeof figma.variables.getLocalVariableCollectionsAsync !== "function") {
        return [];
    }

    try {
        return await figma.variables.getLocalVariableCollectionsAsync();
    } catch (error: unknown) {
        warnings.push(
            `Could not read Figma variable collections: ${getErrorMessage(error)}. `
                + "Exporting a single tokens.json file.",
        );
        return [];
    }
}

function getModeId(variable: Variable, modeExport: ModeExport): string | undefined {
    const collectionModeId = modeExport.modeIdByCollectionId.get(variable.variableCollectionId);
    if (collectionModeId !== undefined && collectionModeId in variable.valuesByMode) {
        return collectionModeId;
    }

    if (modeExport.fileName === "tokens.json") {
        return Object.keys(variable.valuesByMode)[0];
    }

    return undefined;
}

function toTokenValue(
    value: ExportVariableValue | undefined,
    variablePathIndex: VariablePathIndex,
    variableTokenTypeIndex: VariableTokenTypeIndex,
    variableIndex: VariableIndex,
    modeExport: ModeExport,
    tokenType: DtcgVariableTokenType,
): FigmaColor | DtcgColorValue | number | string | undefined {
    if (value === undefined) {
        return undefined;
    }

    if (isVariableAlias(value)) {
        const targetId = resolveAliasTargetId(
            value,
            tokenType,
            variableTokenTypeIndex,
            variableIndex,
            modeExport,
            new Set(),
        );
        const path = targetId === undefined ? undefined : variablePathIndex.get(targetId);
        return path === undefined ? undefined : toDtcgReference(path);
    }

    if (isComposedColorValue(value)) {
        return tokenType === "color"
            ? toComposedDtcgColor(value, variablePathIndex, variableTokenTypeIndex, variableIndex, modeExport)
            : undefined;
    }

    if (tokenType === "color" && isColorValue(value)) {
        return value;
    }

    if ((tokenType === "dimension" || tokenType === "number" || tokenType === "fontWeight") && typeof value === "number") {
        return value;
    }

    return undefined;
}

function isColorValue(value: ExportVariableValue): value is FigmaColor {
    return typeof value === "object"
        && value !== null
        && "r" in value
        && "g" in value
        && "b" in value;
}

function isVariableAlias(value: ExportVariableValue): value is VariableAlias {
    return typeof value === "object"
        && value !== null
        && "type" in value
        && value.type === "VARIABLE_ALIAS";
}

function isComposedColorValue(value: ExportVariableValue): value is VariableComposedColor {
    return typeof value === "object"
        && value !== null
        && "color" in value
        && "opacity" in value;
}

function toComposedDtcgColor(
    value: VariableComposedColor,
    variablePathIndex: VariablePathIndex,
    variableTokenTypeIndex: VariableTokenTypeIndex,
    variableIndex: VariableIndex,
    modeExport: ModeExport,
): DtcgColorValue | undefined {
    const color = toDtcgColorPart(
        value.color,
        variablePathIndex,
        variableTokenTypeIndex,
        variableIndex,
        modeExport,
    );
    const alpha = toDtcgAlphaPart(
        value.opacity,
        variablePathIndex,
        variableTokenTypeIndex,
        variableIndex,
        modeExport,
    );
    return color === undefined || alpha === undefined
        ? undefined
        : { ...color, alpha };
}

function toDtcgColorPart(
    value: ExportVariableValue,
    variablePathIndex: VariablePathIndex,
    variableTokenTypeIndex: VariableTokenTypeIndex,
    variableIndex: VariableIndex,
    modeExport: ModeExport,
): Omit<DtcgColorValue, "alpha"> | undefined {
    if (isColorValue(value)) {
        return {
            colorSpace: "srgb",
            components: [value.r, value.g, value.b],
        };
    }

    if (!isVariableAlias(value)) return undefined;
    const targetId = resolveAliasTargetId(
        value,
        "color",
        variableTokenTypeIndex,
        variableIndex,
        modeExport,
        new Set(),
    );
    const path = targetId === undefined ? undefined : variablePathIndex.get(targetId);
    if (path === undefined) return undefined;
    return {
        colorSpace: toDtcgPropertyReference(path, "colorSpace"),
        components: toDtcgPropertyReference(path, "components"),
    };
}

function toDtcgAlphaPart(
    value: number | VariableAlias,
    variablePathIndex: VariablePathIndex,
    variableTokenTypeIndex: VariableTokenTypeIndex,
    variableIndex: VariableIndex,
    modeExport: ModeExport,
): number | DtcgPropertyReference | undefined {
    if (typeof value === "number") return value;
    const targetId = resolveAliasTargetId(
        value,
        "number",
        variableTokenTypeIndex,
        variableIndex,
        modeExport,
        new Set(),
    );
    const path = targetId === undefined ? undefined : variablePathIndex.get(targetId);
    return path === undefined ? undefined : toDtcgPropertyReference(path);
}

function resolveAliasTargetId(
    alias: VariableAlias,
    expectedType: DtcgVariableTokenType,
    variableTokenTypeIndex: VariableTokenTypeIndex,
    variableIndex: VariableIndex,
    modeExport: ModeExport,
    visitedVariableIds: Set<string>,
): string | undefined {
    if (visitedVariableIds.has(alias.id)) return undefined;

    const variable = variableIndex.get(alias.id);
    if (variable === undefined) return undefined;
    const indexedType = variableTokenTypeIndex.get(alias.id);
    if (expectedType === "number") {
        if (indexedType !== "number" && !isContextuallyNumericVariable(variable, indexedType)) return undefined;
    } else if (indexedType !== expectedType) {
        return undefined;
    }
    const modeId = getModeId(variable, modeExport);
    const targetValue = modeId === undefined ? undefined : variable.valuesByMode[modeId];
    if (targetValue === undefined) return undefined;

    const nextVisitedVariableIds = new Set(visitedVariableIds).add(alias.id);
    if (isVariableAlias(targetValue)) {
        return resolveAliasTargetId(
            targetValue,
            expectedType,
            variableTokenTypeIndex,
            variableIndex,
            modeExport,
            nextVisitedVariableIds,
        );
    }

    if (expectedType === "color") {
        const isResolvableColor = isColorValue(targetValue)
            || isComposedColorValue(targetValue)
                && isResolvableComposedColor(
                    targetValue,
                    variableTokenTypeIndex,
                    variableIndex,
                    modeExport,
                    nextVisitedVariableIds,
                );
        return isResolvableColor ? alias.id : undefined;
    }
    return typeof targetValue === "number" ? alias.id : undefined;
}

function isContextuallyNumericVariable(variable: Variable, tokenType: DtcgVariableTokenType | undefined): boolean {
    return tokenType === "dimension" && isNumberVariable(variable);
}

function isResolvableComposedColor(
    value: VariableComposedColor,
    variableTokenTypeIndex: VariableTokenTypeIndex,
    variableIndex: VariableIndex,
    modeExport: ModeExport,
    visitedVariableIds: Set<string>,
): boolean {
    const colorResolvable = isColorValue(value.color)
        || isVariableAlias(value.color)
            && resolveAliasTargetId(
                value.color,
                "color",
                variableTokenTypeIndex,
                variableIndex,
                modeExport,
                visitedVariableIds,
            ) !== undefined;
    const alphaResolvable = typeof value.opacity === "number"
        || resolveAliasTargetId(
            value.opacity,
            "number",
            variableTokenTypeIndex,
            variableIndex,
            modeExport,
            visitedVariableIds,
        ) !== undefined;

    return colorResolvable && alphaResolvable;
}

function isVisibleSolidPaint(paint: Paint): paint is SolidPaint {
    return paint.type === "SOLID" && paint.visible !== false;
}

function createToken(
    tokenType: DtcgVariableTokenType,
    value: FigmaColor | DtcgColorValue | number | string,
    description: string,
): DtcgToken {
    const token: DtcgToken = createTokenWithoutDescription(tokenType, value);

    if (description.trim() !== "") {
        token.$description = description;
    }

    return token;
}

function createTokenWithoutDescription(
    tokenType: DtcgVariableTokenType,
    value: FigmaColor | DtcgColorValue | number | string,
): DtcgToken {
    if (tokenType === "color") {
        return {
            $type: "color",
            $value: typeof value === "string"
                ? value
                : isDtcgColorValue(value) ? value : toDtcgColorValue(value as FigmaColor),
        };
    }

    if (tokenType === "dimension") {
        return {
            $type: "dimension",
            $value: typeof value === "string" ? value : { value: value as number, unit: "px" },
        };
    }

    if (tokenType === "fontWeight") {
        return {
            $type: "fontWeight",
            $value: value as number | string,
        };
    }

    return {
        $type: "number",
        $value: value as number | string,
    };
}

function createTypographyToken(style: TextStyle): DtcgTypographyToken {
    const token: DtcgTypographyToken = {
        $type: "typography",
        $value: {
            fontFamily: style.fontName.family,
            fontSize: toDimensionValue(style.fontSize),
            fontWeight: toFontWeight(style.fontName.style),
            letterSpacing: toLetterSpacingValue(style.letterSpacing, style.fontSize),
            lineHeight: toLineHeightValue(style.lineHeight, style.fontSize),
        },
    };

    if (style.description.trim() !== "") {
        token.$description = style.description;
    }

    return token;
}

function createShadowToken(layers: DtcgShadowLayer[], description: string): DtcgShadowToken {
    const token: DtcgShadowToken = {
        $type: "shadow",
        $value: layers.length === 1 ? layers[0]! : layers,
    };

    if (description.trim() !== "") {
        token.$description = description;
    }

    return token;
}

function isShadowEffect(effect: Effect): effect is DropShadowEffect | InnerShadowEffect {
    return effect.type === "DROP_SHADOW" || effect.type === "INNER_SHADOW";
}

function isVisibleShadowEffect(effect: Effect): effect is DropShadowEffect | InnerShadowEffect {
    return isShadowEffect(effect) && effect.visible !== false;
}

function toShadowLayer(effect: DropShadowEffect | InnerShadowEffect): DtcgShadowLayer {
    const layer: DtcgShadowLayer = {
        color: toDtcgColorValue(effect.color),
        offsetX: toDimensionValue(effect.offset.x),
        offsetY: toDimensionValue(effect.offset.y),
        blur: toDimensionValue(effect.radius),
        spread: toDimensionValue(effect.spread ?? 0),
    };

    if (effect.type === "INNER_SHADOW") {
        layer.inset = true;
    }

    return layer;
}

function toDimensionValue(value: number): DtcgDimensionValue {
    return { value, unit: "px" };
}

function toLetterSpacingValue(letterSpacing: LetterSpacing, fontSize: number): DtcgDimensionValue {
    if (letterSpacing.unit === "PERCENT") {
        return toDimensionValue((letterSpacing.value / 100) * fontSize);
    }

    return toDimensionValue(letterSpacing.value);
}

function toLineHeightValue(lineHeight: LineHeight, fontSize: number): number {
    if (lineHeight.unit === "AUTO") {
        return 1;
    }

    if (lineHeight.unit === "PERCENT") {
        return lineHeight.value / 100;
    }

    return lineHeight.value / fontSize;
}

function toFontWeight(fontStyle: string): number {
    const normalized = fontStyle.toLowerCase().replace(/[^a-z0-9]+/g, "-");
    if (normalized.includes("thin") || normalized.includes("hairline")) return 100;
    if (normalized.includes("extra-light") || normalized.includes("ultra-light")) return 200;
    if (normalized.includes("light")) return 300;
    if (normalized.includes("medium")) return 500;
    if (normalized.includes("semi-bold") || normalized.includes("demi-bold")) return 600;
    if (normalized.includes("extra-bold") || normalized.includes("ultra-bold")) return 800;
    if (normalized.includes("black") || normalized.includes("heavy")) return 900;
    if (normalized.includes("bold")) return 700;
    return 400;
}

function toDtcgColorValue(color: FigmaColor): DtcgColorValue {
    return {
        colorSpace: "srgb",
        components: [color.r, color.g, color.b],
        alpha: color.a ?? 1,
    };
}

function isDtcgColorValue(value: FigmaColor | DtcgColorValue | number): value is DtcgColorValue {
    return typeof value === "object" && value !== null && "colorSpace" in value && "components" in value;
}

function toDtcgPropertyReference(path: string[], property?: string): DtcgPropertyReference {
    const pointerPath = property === undefined ? [...path, "$value"] : [...path, "$value", property];
    return { $ref: `#/${pointerPath.map(escapeJsonPointerSegment).join("/")}` };
}

function escapeJsonPointerSegment(segment: string): string {
    return encodeURIComponent(segment.replace(/~/g, "~0").replace(/\//g, "~1")).replace(/%24/gi, "$");
}

function toDtcgReference(path: string[]): string {
    return `{${path.join(".")}}`;
}

function slugifyFileName(value: string): string {
    return value
        .trim()
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-+|-+$/g, "") || "theme";
}

function getErrorMessage(error: unknown): string {
    if (error instanceof Error && error.message.trim() !== "") {
        return error.message;
    }

    if (typeof error === "string" && error.trim() !== "") {
        return error;
    }

    return "unknown error";
}

export type DtcgToken =
    | DtcgColorToken
    | DtcgDimensionToken
    | DtcgFontWeightToken
    | DtcgNumberToken
    | DtcgTypographyToken
    | DtcgShadowToken;

export type DtcgVariableTokenType =
    | DtcgColorToken["$type"]
    | DtcgDimensionToken["$type"]
    | DtcgFontWeightToken["$type"]
    | DtcgNumberToken["$type"];

type FigmaColor = RGB & Partial<Pick<RGBA, "a">>;

type VariableComposedColor = {
    color: FigmaColor | VariableAlias;
    opacity: number | VariableAlias;
};

type ExportVariableValue = VariableValue | VariableComposedColor;

type VariablePathIndex = Map<string, string[]>;

type VariableTokenTypeIndex = Map<string, DtcgVariableTokenType>;

type VariableIndex = Map<string, Variable>;
